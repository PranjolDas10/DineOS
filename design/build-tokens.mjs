// Generates web/src/app/tokens.css from design/tokens.json and fails if a listed color pair
// is below its WCAG contrast minimum. CI reruns it and fails on drift.
// Usage: node design/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("design/tokens.json", root), "utf8"));

const primitive = (ref) => {
  const value = ref.split(".").reduce((node, key) => node?.[key], tokens.primitive);
  if (typeof value !== "string") throw new Error(`Unknown primitive "${ref}"`);
  return value;
};

// WCAG 2.x relative luminance and contrast ratio.
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const failures = [];
const block = (theme) => {
  const resolved = Object.fromEntries(
    Object.entries(tokens.semantic[theme]).map(([name, ref]) => [name, primitive(ref)]),
  );
  for (const [fg, bg, min] of tokens.contrast.pairs) {
    const ratio = contrast(resolved[fg], resolved[bg]);
    if (ratio < min) failures.push(`${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`);
  }
  return Object.entries(resolved)
    .map(([name, hex]) => `  --${name}: ${hex};`)
    .join("\n");
};

const radius = Object.entries(tokens.radius)
  .map(([name, value]) => `  --radius-${name}: ${value};`)
  .join("\n");
const css = `/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${block("light")}
${radius}
}

@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${block("dark").replaceAll("\n  ", "\n    ").replace(/^ {2}/, "    ")}
  }
}
`;

if (failures.length) {
  console.error(`Contrast check failed:\n${failures.join("\n")}`);
  process.exit(1);
}
writeFileSync(new URL("web/src/app/tokens.css", root), css);
console.log("Wrote web/src/app/tokens.css");
