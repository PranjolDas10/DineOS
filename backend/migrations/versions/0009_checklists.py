TENANT_TABLES = ["checklist_templates", "checklist_runs", "checklist_checks", "alerts"]


def upgrade() -> None:
    # At-most-once scheduled jobs: one "materialize day D" job per tenant per day, ever.
    # NULL keys never conflict, so ordinary jobs are unaffected.
    op.execute("ALTER TABLE jobs ADD COLUMN dedupe_key text")
    op.execute("ALTER TABLE jobs ADD CONSTRAINT jobs_dedupe_key UNIQUE (tenant_id, dedupe_key)")

    # items: [{"id": uuid, "label": text}], edited as one versioned unit with the template.
    # due_minutes: minutes after local midnight of the business day; > 1440 = after midnight
    # (a closing checklist due 01:00 is 1500).
    op.execute("""
        CREATE TABLE checklist_templates (
            id uuid PRIMARY KEY DEFAULT uuidv7(),
            tenant_id uuid NOT NULL DEFAULT current_tenant_id() REFERENCES tenants (id),
            name text NOT NULL,
            days_of_week smallint[] NOT NULL
                CHECK (cardinality(days_of_week) > 0 AND days_of_week <@ '{0,1,2,3,4,5,6}'),
            due_minutes integer NOT NULL CHECK (due_minutes BETWEEN 0 AND 2880),
            items jsonb NOT NULL,
            active boolean NOT NULL DEFAULT true,
            version integer NOT NULL DEFAULT 1,
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (tenant_id, id)
        )
    """)

    # One run per template per business day. items is a snapshot: editing the template
    # tonight doesn't change the checklist people are already ticking off.
    op.execute("""
        CREATE TABLE checklist_runs (
            id uuid PRIMARY KEY DEFAULT uuidv7(),
            tenant_id uuid NOT NULL DEFAULT current_tenant_id() REFERENCES tenants (id),
            template_id uuid NOT NULL,
            name text NOT NULL,
            business_date date NOT NULL,
            due_at timestamptz NOT NULL,
            items jsonb NOT NULL,
            completed_at timestamptz,
            alerted_at timestamptz,
            created_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (template_id, business_date),
            UNIQUE (tenant_id, id),
            FOREIGN KEY (tenant_id, template_id) REFERENCES checklist_templates (tenant_id, id)
        )
    """)

    # Append-only check/uncheck events. id is generated by the phone (offline op id), so a
    # replayed sync is a no-op. An item's state = its event with the latest checked_at.
    op.execute("""
        CREATE TABLE checklist_checks (
            id uuid PRIMARY KEY,
            tenant_id uuid NOT NULL DEFAULT current_tenant_id() REFERENCES tenants (id),
            run_id uuid NOT NULL,
            item_id uuid NOT NULL,
            checked boolean NOT NULL,
            checked_at timestamptz NOT NULL,
            created_at timestamptz NOT NULL DEFAULT now(),
            FOREIGN KEY (tenant_id, run_id) REFERENCES checklist_runs (tenant_id, id)
                ON DELETE CASCADE
        )
    """)
    op.execute(
        "CREATE INDEX checklist_checks_run_idx ON checklist_checks (tenant_id, run_id, item_id)"
    )

    # Owner-facing notifications. Delivery (FCM push) is added with the Android app;
    # this table is the in-app alert list either way.
    op.execute("""
        CREATE TABLE alerts (
            id uuid PRIMARY KEY DEFAULT uuidv7(),
            tenant_id uuid NOT NULL DEFAULT current_tenant_id() REFERENCES tenants (id),
            kind text NOT NULL,
            title text NOT NULL,
            body text NOT NULL,
            read_at timestamptz,
            created_at timestamptz NOT NULL DEFAULT now()
        )
    """)

    for table in TENANT_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY tenant_isolation ON {table} USING (tenant_id = current_tenant_id())"
        )


